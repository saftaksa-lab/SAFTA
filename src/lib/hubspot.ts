// Region names Intl gets wrong for this site. The forms say "Palestine".
const countryOverrides: Record<string, string> = { PS: 'فلسطين' };

function arabicCountries(): Record<string, string> {
  const names = new Intl.DisplayNames('ar', { type: 'region' });
  return Object.fromEntries(
    Object.entries(countryCodes).map(([value, code]) => [value, countryOverrides[code] ?? names.of(code) ?? value]),
  );
}

