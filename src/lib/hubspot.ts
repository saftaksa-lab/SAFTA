/**
 * Arabic text for the embedded HubSpot forms (src/components/HubSpotForm.astro).
 *
 * The forms themselves, and their English text, live in HubSpot; Water STRIP
 * embeds the same two forms. In Arabic the embed switches HubSpot to its
 * built-in `ar-eg` locale, which translates HubSpot's own strings (submit
 * button, validation and submission errors, the date picker), and HubSpotForm
 * rewrites the per-form text it cannot: labels, field descriptions and dropdown
 * options. Only the visible text changes; submitted values stay HubSpot's
 * English option values.
 *
 * Copy is keyed by HubSpot's internal field names and option values. A field
 * added in HubSpot and missing here just shows its English text.
 */

export interface HubSpotFormCopy {
  /** HubSpot's own locale code, for the strings HubSpot translates itself. */
  locale: string;
  /** The empty first option of every dropdown. */
  choose: string;
  /** By HubSpot field name. */
  fields: Record<string, { label?: string; description?: string }>;
  /** By HubSpot field name, then option value. */
  options: Record<string, Record<string, string>>;
}

