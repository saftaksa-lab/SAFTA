#!/usr/bin/env node
// Generates src/lib/content/schema/<page>.ts from public/admin/schema.js (the admin UI's
// existing hand-maintained field/section layout) cross-checked against content/<page>.json
// (which key is text vs image). Re-run after adding or removing a field in the admin UI;
// it fails loudly on any mismatch between the two sources rather than emitting a schema
// that's already out of sync with the content store.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const page = process.argv[2];
if (!page) {
  console.error('usage: node scripts/generate-page-schema.mjs <page>');
  process.exit(1);
}

const schemaSrc = readFileSync(resolve('public/admin/schema.js'), 'utf8');
const schemaMatch = schemaSrc.match(/=\s*(\{[\s\S]*?\});?\s*$/m);
if (!schemaMatch) {
  console.error('could not locate the assigned object literal in public/admin/schema.js');
  process.exit(1);
}
const allSchemas = JSON.parse(schemaMatch[1]);
const pageSchema = allSchemas[page];
if (!pageSchema) {
  console.error(`no "${page}" entry in public/admin/schema.js`);
  process.exit(1);
}
if (pageSchema.kind === 'data') {
  console.error(`"${page}" is a data view (kind: "data"), not a flat page — this generator only handles page schemas`);
  process.exit(1);
}

const content = JSON.parse(readFileSync(resolve(`content/${page}.json`), 'utf8'));

function kindOf(key) {
  const record = content[key];
  if (!record) throw new Error(`schema.js references "${key}" but content/${page}.json has no such key`);
  return 'src' in record ? 'image' : 'text';
}

const fields = {};
const sectionsOut = [];

for (const section of pageSchema.sections || []) {
  const fieldKeys = [];
  for (const f of section.fields || []) {
    fields[f.key] = { kind: kindOf(f.key), tag: f.tag, type: f.type, label: f.label };
    fieldKeys.push(f.key);
  }
  const cardsOut = [];
  for (const card of section.cards || []) {
    const cardFieldKeys = [];
    for (const f of card.fields || []) {
      fields[f.key] = { kind: kindOf(f.key), tag: f.tag, type: f.type, label: f.label };
      cardFieldKeys.push(f.key);
    }
    cardsOut.push({ key: card.key, label: card.label, fields: cardFieldKeys });
  }
  sectionsOut.push({ key: section.key, label: section.label, fields: fieldKeys, cards: cardsOut });
}

const contentKeys = Object.keys(content).sort();
const fieldKeysAll = Object.keys(fields).sort();
const missingFromSchema = contentKeys.filter((k) => !fieldKeysAll.includes(k));
const missingFromContent = fieldKeysAll.filter((k) => !contentKeys.includes(k));
if (missingFromSchema.length || missingFromContent.length) {
  console.error(`schema.js and content/${page}.json disagree on the field set:`);
  if (missingFromSchema.length) console.error('  in content, not in schema.js:', missingFromSchema);
  if (missingFromContent.length) console.error('  in schema.js, not in content:', missingFromContent);
  process.exit(1);
}

const ident = page.replace(/[^a-zA-Z0-9]/g, '_').toUpperCase();

function emitFields() {
  return Object.entries(fields)
    .map(
      ([k, v]) =>
        `  ${JSON.stringify(k)}: { kind: ${JSON.stringify(v.kind)}, tag: ${JSON.stringify(v.tag)}, type: ${JSON.stringify(v.type)}, label: ${JSON.stringify(v.label)} },`,
    )
    .join('\n');
}

function emitCard(c) {
  return `      { key: ${JSON.stringify(c.key)}, label: ${JSON.stringify(c.label)}, fields: ${JSON.stringify(c.fields)} },`;
}

function emitSections() {
  return sectionsOut
    .map(
      (s) => `  {
    key: ${JSON.stringify(s.key)},
    label: ${JSON.stringify(s.label)},
    fields: ${JSON.stringify(s.fields)},
    cards: [
${s.cards.map(emitCard).join('\n')}
    ],
  },`,
    )
    .join('\n');
}

const out = `// GENERATED by \`node scripts/generate-page-schema.mjs ${page}\` from public/admin/schema.js
// + content/${page}.json. Re-run after changing the admin's field/section layout for this
// page rather than hand-editing the field list below — the generator fails loudly if the
// two sources disagree, hand edits here can't.
import type { FieldMap } from './codec';

export const ${ident}_FIELDS = {
${emitFields()}
} as const satisfies FieldMap;

export const ${ident}_SECTIONS = [
${emitSections()}
] as const;

const ${ident}_PAGE = {
  label: ${JSON.stringify(pageSchema.label)},
  file: ${JSON.stringify(pageSchema.file)},
  apiBacked: true as const,
  fields: ${ident}_FIELDS,
  sections: ${ident}_SECTIONS,
};

export default ${ident}_PAGE;
`;

const outPath = resolve(`src/lib/content/schema/${page}.ts`);
writeFileSync(outPath, out);
console.log(`wrote ${outPath} (${fieldKeysAll.length} fields, ${sectionsOut.length} sections)`);
